// Package featuregen turns opencode/features.tsv into the generated Feature
// enum and FeatureInfo switch (SPEC §5.8). The table is the single source;
// a test regenerates in memory and fails when the checked-in file drifts.
package featuregen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"strings"
)

// Row is one features.tsv line.
type Row struct {
	Name, Spelling, Since, Until, Source string
}

// TSV layout.
const (
	commentPrefix = "#"
	fieldSep      = "\t"
	minFields     = 2
	colSince      = 2
	colUntil      = 3
	colSource     = 4
)

// ErrNoSource means a row has a bound but no source (invariant 15).
var ErrNoSource = errors.New("featuregen: bound without a source")

// Parse reads features.tsv rows.
func Parse(tsv []byte) ([]Row, error) {
	var rows []Row
	for i, line := range strings.Split(string(tsv), "\n") {
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, commentPrefix) {
			continue
		}
		f := strings.Split(line, fieldSep)
		if len(f) < minFields {
			return nil, fmt.Errorf("featuregen: line %d: want at least %d fields", i+1, minFields)
		}
		get := func(n int) string {
			if n < len(f) {
				return strings.TrimSpace(f[n])
			}
			return ""
		}
		r := Row{Name: get(0), Spelling: get(1), Since: get(colSince), Until: get(colUntil), Source: get(colSource)}
		if (r.Since != "" || r.Until != "") && r.Source == "" {
			return nil, fmt.Errorf("%w: line %d (%s)", ErrNoSource, i+1, r.Name)
		}
		rows = append(rows, r)
	}
	return rows, nil
}

// Generate renders the Go source for package opencode.
func Generate(tsv []byte) ([]byte, error) {
	rows, err := Parse(tsv)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/featuregen from features.tsv; DO NOT EDIT.\n\npackage opencode\n\n")
	b.WriteString("import \"github.com/ubgo/agentio\"\n\n")
	b.WriteString("// Feature values, one per features.tsv row.\nconst (\n\t// FeatureUnknown is the zero Feature.\n\tFeatureUnknown Feature = iota\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t// Feature%s is %q.\n\tFeature%s\n", r.Name, r.Spelling, r.Name)
	}
	b.WriteString(")\n\n// String is the vendor spelling. Pure.\nfunc (f Feature) String() string {\n\tswitch f {\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\tcase Feature%s:\n\t\treturn %q\n", r.Name, r.Spelling)
	}
	b.WriteString("\t}\n\treturn \"unknown\"\n}\n\n")
	b.WriteString("// Features lists every Feature in table order (the same name as\n// claude.Features). Pure.\nfunc Features() []Feature {\n\treturn []Feature{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t\tFeature%s,\n", r.Name)
	}
	b.WriteString("\t}\n}\n\n")
	b.WriteString("// FeatureInfo is the verified Since/Until span of f; zero bounds are unknown. Pure.\nfunc FeatureInfo(f Feature) agentio.FeatureSpan {\n\tswitch f {\n")
	for _, r := range rows {
		if r.Since == "" && r.Until == "" {
			continue
		}
		fmt.Fprintf(&b, "\tcase Feature%s: // %s\n\t\treturn agentio.FeatureSpan{Since: %s, Until: %s}\n", r.Name, r.Source, versionExpr(r.Since), versionExpr(r.Until))
	}
	b.WriteString("\t}\n\treturn agentio.FeatureSpan{}\n}\n\n")
	b.WriteString("// featureSource names the release note of f's bounds; \"\" when unknown. Pure.\nfunc featureSource(f Feature) string {\n\tswitch f {\n")
	for _, r := range rows {
		if r.Source == "" {
			continue
		}
		fmt.Fprintf(&b, "\tcase Feature%s:\n\t\treturn %q\n", r.Name, r.Source)
	}
	b.WriteString("\t}\n\treturn \"\"\n}\n")
	return format.Source(b.Bytes())
}

func versionExpr(v string) string {
	if v == "" {
		return "agentio.Version{}"
	}
	return fmt.Sprintf("agentio.MustVersion(%q)", v)
}
