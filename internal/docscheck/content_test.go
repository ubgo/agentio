package docscheck

import (
	"strings"
	"testing"
)

// localPathMarkers are prefixes of real machine paths that must never reach
// public files; examples use /home/user, /work/project or $HOME instead.
var localPathMarkers = []string{"/Users/", "/Volumes/", "/home/khanakia", "/space/"}

// attributionPhrases are authoring-attribution phrases (matched lowercase).
// Product names the library is about ("Claude Code", "Codex", and Codex's ChatGPT login mode) are not here:
// naming the subject of the library is required, crediting a tool is not.
var attributionPhrases = []string{
	"co-authored-by", "generated with", "generated by ai", "claude code-generated",
	"written by claude", "ai-generated", "ai assistant", "copilot",
}

// scannedFiles are the public markdown files plus the Go files under
// examples/ and docs/. Every line is scanned, fenced code included.
func scannedFiles(t *testing.T, root string) []string {
	t.Helper()
	var out []string
	for _, f := range candidateFiles(t, root) {
		if isPublicMarkdown(f) || isCheckedGo(f) {
			out = append(out, f)
		}
	}
	return out
}

// firstPhrase returns the first phrase line contains, or "". fold lowercases
// the line first (the phrases must then be lowercase).
func firstPhrase(line string, phrases []string, fold bool) string {
	if fold {
		line = strings.ToLower(line)
	}
	for _, p := range phrases {
		if strings.Contains(line, p) {
			return p
		}
	}
	return ""
}

func TestNoLocalPaths(t *testing.T) {
	root := repoRoot(t)
	for _, f := range scannedFiles(t, root) {
		for i, l := range readLines(t, root, f) {
			if p := firstPhrase(l, localPathMarkers, false); p != "" {
				t.Errorf("%s:%d: local machine path %q (use /home/user, /work/project or $HOME)", f, i+1, p)
			}
		}
	}
}

func TestNoAttribution(t *testing.T) {
	root := repoRoot(t)
	for _, f := range scannedFiles(t, root) {
		for i, l := range readLines(t, root, f) {
			if p := firstPhrase(l, attributionPhrases, true); p != "" {
				t.Errorf("%s:%d: authoring attribution %q", f, i+1, p)
			}
		}
	}
}
