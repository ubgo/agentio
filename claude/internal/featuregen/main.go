// Command featuregen writes claude/features_gen.go from claude/features.tsv:
// the Feature constants, their vendor spellings, and the FeatureInfo /
// featureSource switches. Run through `go generate` in the claude package.
// Why generated: the table is data verified by hand against the vendor
// CHANGELOG, and a switch keeps it out of package-level vars (SPEC §5.8).
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// File names relative to the claude package dir (go generate's cwd).
const (
	tsvFile  = "features.tsv"
	outFile  = "features_gen.go"
	fieldSep = "\t"
	comment  = "#"
	// columns is name, spelling, since, until, source.
	columns = 5
	outPerm = 0o644
)

// row is one feature.
type row struct{ name, spelling, since, until, source string }

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "featuregen:", err)
		os.Exit(1)
	}
}

func run() error {
	data, err := os.ReadFile(tsvFile)
	if err != nil {
		return err
	}
	rows, err := parse(data)
	if err != nil {
		return err
	}
	src, err := format.Source(render(rows))
	if err != nil {
		return err
	}
	return os.WriteFile(outFile, src, outPerm)
}

func parse(data []byte) ([]row, error) {
	var rows []row
	sc := bufio.NewScanner(bytes.NewReader(data))
	for n := 1; sc.Scan(); n++ {
		line := sc.Text()
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, comment) {
			continue
		}
		f := strings.Split(line, fieldSep)
		if len(f) != columns {
			return nil, fmt.Errorf("%s:%d: %d columns, want %d", tsvFile, n, len(f), columns)
		}
		r := row{name: f[0], spelling: f[1], since: f[2], until: f[3], source: f[4]}
		if (r.since != "" || r.until != "") && r.source == "" {
			return nil, fmt.Errorf("%s:%d: %s has a bound but no source", tsvFile, n, r.name)
		}
		rows = append(rows, r)
	}
	return rows, sc.Err()
}

func render(rows []row) []byte {
	var b bytes.Buffer
	// p substitutes args into the %s slots in order; spellings and
	// sources never contain %s.
	p := func(format string, args ...string) {
		s := format
		for _, a := range args {
			s = strings.Replace(s, "%s", a, 1)
		}
		b.WriteString(s)
	}
	p("// Code generated by internal/featuregen from features.tsv; DO NOT EDIT.\n\npackage claude\n\nimport \"github.com/ubgo/agentio\"\n\n")
	p("// Feature constants, one per features.tsv row.\nconst (\n\t// FeatureUnknown is the zero value.\n\tFeatureUnknown Feature = iota\n")
	for _, r := range rows {
		p("\t// Feature%s is %s.\n\tFeature%s\n", r.name, quoteless(r.spelling), r.name)
	}
	p(")\n\n// featureSpellings is indexed by Feature.\nfunc featureSpellings() []string {\n\treturn []string{\"unknown\",\n")
	for _, r := range rows {
		p("\t\t%s,\n", quote(r.spelling))
	}
	p("\t}\n}\n\n// FeatureInfo returns the versions a feature exists in; zero bounds are\n// unknown, never invented (invariant 15). cost: Pure.\nfunc FeatureInfo(f Feature) agentio.FeatureSpan {\n\tswitch f {\n")
	for _, r := range rows {
		if r.since == "" && r.until == "" {
			continue
		}
		p("\tcase Feature%s:\n\t\treturn agentio.FeatureSpan{Since: agentio.MustVersion(%s), Until: agentio.MustVersion(%s)}\n", r.name, quote(r.since), quote(r.until))
	}
	p("\t}\n\treturn agentio.FeatureSpan{}\n}\n\n// featureSource names the CHANGELOG line behind a bound. cost: Pure.\nfunc featureSource(f Feature) string {\n\tswitch f {\n")
	for _, r := range rows {
		if r.source == "" {
			continue
		}
		p("\tcase Feature%s:\n\t\treturn %s\n", r.name, quote(r.source))
	}
	p("\t}\n\treturn \"\"\n}\n")
	return b.Bytes()
}

func quote(s string) string { return fmt.Sprintf("%q", s) }

// quoteless keeps a comment on one line.
func quoteless(s string) string { return strings.ReplaceAll(s, "\n", " ") }
